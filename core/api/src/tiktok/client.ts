/**
 * Contract for the TikTok OAuth client used by the API and worker.
 *
 * Mirrors `GoogleOAuthClient` so the rest of the codebase (auth routes,
 * worker token refresh) can swap implementations without changing call sites.
 *
 * TikTok differences vs Google:
 *   - PKCE (S256) is required for all public clients. The verifier/code
 *     challenge pair must round-trip through the start/callback handlers.
 *   - Access tokens are short-lived (24h) — the refresh_token is the durable
 *     secret and is always returned on first consent.
 *   - Scopes are space-separated; `video.upload` and `video.publish` are what
 *     the Content Posting API needs.
 */
export interface TiktokTokens {
  access_token: string;
  /** Unix epoch in milliseconds. */
  expires_at: number;
  refresh_token: string;
  /** Space-separated scopes the user granted. */
  scope: string;
  token_type: string;
  /** Opaque open_id that identifies the TikTok user — stable per install. */
  open_id: string;
}

export interface TiktokUserInfo {
  open_id: string;
  /** TikTok display name. */
  display_name: string;
  /** Profile avatar URL. */
  avatar_url: string;
}

export interface TiktokOAuthClient {
  /**
   * Generate the auth URL the user should be redirected to. The PKCE
   * verifier/code_challenge pair MUST be generated by the caller and passed
   * in — the client only knows how to URL-encode them.
   */
  buildAuthUrl(state: string, codeChallenge: string): string;
  /** Exchange `code` + `codeVerifier` for tokens. */
  exchangeCode(code: string, codeVerifier: string): Promise<TiktokTokens>;
  /** Use refresh_token to get a new access_token (and rotated refresh_token). */
  refresh(refreshToken: string): Promise<TiktokTokens>;
  /** Return the logged-in user's profile. */
  getMyUser(accessToken: string): Promise<TiktokUserInfo>;
}
